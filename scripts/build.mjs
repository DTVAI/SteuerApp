// Dependency-free static build. Cache revisions reflect every shipped asset.
import { readdir, readFile, writeFile, mkdir, rm, copyFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = ['index.html', 'styles.css', 'manifest.webmanifest', 'sw.js', 'docs/storage-setup.md', '_headers'];
async function collect(dir) { for (const entry of await readdir(path.join(root, dir), { withFileTypes: true })) { const name = dir + '/' + entry.name; if (entry.isDirectory()) await collect(name); else files.push(name); } }
for (const dir of ['js', 'vendor', 'icons']) await collect(dir);
files.sort(); const hash = createHash('sha256');
for (const file of files) { await access(path.join(root, file)); hash.update(file); hash.update(await readFile(path.join(root, file))); }
const revision = hash.digest('hex').slice(0, 20);
const assets = files.filter((file) => !['sw.js', '_headers'].includes(file));
await writeFile(path.join(root, 'asset-manifest.js'), `// Generated by scripts/build.mjs\nexport const CACHE_NAME = 'belegwerk-shell-${revision}';\nexport const SHELL_ASSETS = ${JSON.stringify(assets.map((name) => './' + name), null, 2)};\n`);
await rm(path.join(root, 'dist'), { recursive: true, force: true });
for (const file of [...files, 'asset-manifest.js']) { const target = path.join(root, 'dist', file); await mkdir(path.dirname(target), { recursive: true }); await copyFile(path.join(root, file), target); }
console.log(`Built Belegwerk ${revision}: ${files.length + 1} files in dist/`);
